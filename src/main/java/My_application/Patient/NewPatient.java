    private void enregistrer() {
        NouveauPatientController.Saisie s = new NouveauPatientController.Saisie();
        s.numero = jTextField1.getText();
        s.numeroSecuriteSociale = jTextField6.getText();
        s.nom = jTextField7.getText();
        s.prenom = jTextField8.getText();
        s.dateNaissance = jTextField9.getText();
        s.masculin = jComboBox1.getSelectedIndex() == 0;
        s.situationMaritale = String.valueOf(jComboBox2.getSelectedItem());
        patientCree = controleur.enregistrer(s);
        if (patientCree != null) {
            dispose();
        }
    }

    /** Patient enregistré, ou null si la fiche a été annulée. */
    public patient getPatientCree() {
        return patientCree;
    }

