    public OrdonnanceForm(consultation consult, CatalogueService catalogue) {
        this.catalogue = catalogue;
        initComponents();
        Theme.harmoniser(this);
        // L'ancien bandeau « ORDONNANCE » laisse la place à l'en-tête commun.
        jPanel1.setVisible(false);
        EnTetePage.installer(this, "prescription", "Ordonnance", consult.getPatient().getNom().toUpperCase()
                + " " + consult.getPatient().getPrenom() + "  ·  " + consult.getPatient().getStringAge());
        pack();
        this.consult = consult;
        this.setLocationRelativeTo(null);
        this.validerBtn.setEnabled(false);
        controleur = new CatalogueController(this, catalogue);
        model = new my_modelOrdonnance(consult.getOrdoPat().getMedicaments());
        nomLab.setText(consult.getPatient().getNom());
        prenomLab.setText(consult.getPatient().getPrenom());
        ageLab.setText(consult.getPatient().getStringAge());
        moment.addItem("");
        this.setModal(true);
        table.setModel(model);
        table.getColumnModel().getColumn(1).setCellRenderer(rondu);
        table.getColumnModel().getColumn(2).setCellRenderer(rondu);
        table.getColumnModel().getColumn(3).setCellRenderer(rondu);
        table.getColumnModel().getColumn(4).setCellRenderer(rondu);
        table.getColumnModel().getColumn(0).setPreferredWidth(400);
        AutoCompletion.installer(choix, Boxmodel, true, new AutoCompletion.Source<medicament>() {
            @Override
            public List<medicament> suggestions(String prefixe) {
                return controleur.rechercherMedicaments(prefixe);
            }
        });
        initialiser();
        choix.requestFocus();
    }

