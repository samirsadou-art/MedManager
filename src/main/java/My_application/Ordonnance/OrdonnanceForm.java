    private void tableKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tableKeyReleased
        
        if(table.getSelectedRowCount()>0)
         if(evt.getKeyChar()==KeyEvent.VK_DELETE){
             suprimer_ligne();
             if(model.getRowCount()==0){
                 this.validerBtn.setEnabled(false);
                
             }
         }
         else{
             table.clearSelection();
       
          
           initialiser();}
         
        
    }//GEN-LAST:event_tableKeyReleased

    private void tableMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseReleased
        
       
         if(SwingUtilities.isRightMouseButton(evt)){
             table.clearSelection();
             initialiser();
            
         }
         else
       if(table.getSelectedRowCount()==1){
        choix.setEnabled(false);
        suppBtn.setEnabled(true);
        modBtn.setEnabled(true);
        addBtn.setEnabled(false);
        int index=table.getSelectedRow();
         
        medicament medic= model.getMedicament(index);
        choix.removeAllItems();
        choix.addItem(medic.getDesignmed().toString());
       choix.setSelectedIndex(0);
  
        unite.setSelectedItem(String.valueOf(medic.getUnite()));
        
        posologie.setSelectedItem(String.valueOf(medic.getPosologie()));
        if(medic.getMode()==0)
        
          moment.setSelectedIndex(0);
        else 
          if(medic.getMode()==1)
            moment.setSelectedIndex(1);
        else
             moment.setSelectedIndex(2); 
        if(medic.getDuree()==0)
            duree.setText("");
        else
        duree.setText(String.valueOf(medic.getDuree()));      
  
         }  
       else
       {  
        initialiser();
        suppBtn.setEnabled(true);
        addBtn.setEnabled(false);
        modBtn.setEnabled(false);
                
  
       }
       
         
            
    }//GEN-LAST:event_tableMouseReleased

