    public void initialiser(){
        choix.removeAllItems();
        choix.setSelectedItem("");
        choix.requestFocus();
        unite.setSelectedIndex(0);
        posologie.setSelectedIndex(0);
        moment.setSelectedIndex(2);
        duree.setText("");
        addBtn.setEnabled(true);
        suppBtn.setEnabled(false);
        modBtn.setEnabled(false);

    }
    
  
  
    
    
    
    public void InsererMed() {
        String saisie = AutoCompletion.saisie(choix);
        if (saisie.isEmpty()) {
            return;
        }
        medicament choisi = AutoCompletion.selection(choix, medicament.class);
        if (choisi == null) {
            JOptionPane.showMessageDialog(this, "Veuillez insérer le médicament dans la base de données !",
                    " Le médicament n'existe pas", JOptionPane.WARNING_MESSAGE);
            AddMedicamentForm addM = new AddMedicamentForm(catalogue);
            addM.setNomMED(saisie);
            addM.setVisible(true);
            choisi = addM.getMedicamentCree();
            if (choisi == null) {
                return;
            }
        }
        medicament medic = new medicament();
        medic.setIdmed(choisi.getIdmed());
        medic.setDesignmed(choisi.getDesignmed());
        lirePrescription(medic);
        if (!model.ajout(medic)) {
            afficherErreur("Ce médicament figure déjà sur l'ordonnance.");
        }
        validerBtn.setEnabled(model.getRowCount() > 0);
    }

    /** Recopie les champs unités / posologie / moment / durée dans le médicament. */
    private void lirePrescription(medicament medic) {
        medic.setUnite(Integer.parseInt(unite.getSelectedItem().toString()));
        medic.setPosologie(Integer.parseInt(posologie.getSelectedItem().toString()));
        int m = moment.getSelectedIndex();
        medic.setMode(m == 0 ? medicament.MODE_SOIR : m == 1 ? medicament.MODE_MATIN : medicament.MODE_INDIFFERENT);
        String d = duree.getText().trim();
        medic.setDuree(d.isEmpty() ? 0 : Integer.parseInt(d));
    }

