    private void tableMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseReleased
         if(SwingUtilities.isRightMouseButton(evt)){
             table.clearSelection();
             initialiser();
         }
         else
             
             if(table.getSelectedRowCount()==1 && !bilanChek.isSelected() ){
        int index=table.getSelectedRow();
         
        analyse ana= model.getAnal(index);
        designCombo.removeAllItems();
        designCombo.addItem(ana.getDesign().toString());
        designCombo.setSelectedIndex(0);
        obsText.setText(ana.getObserv());
        suppBtn.setEnabled(true);
        modBtn.setEnabled(true);
        addBtn.setEnabled(false);
        designCombo.setEnabled(false);
        
 
     
        
             }
             else{
                 
                    designCombo.removeAllItems();
                    designCombo.setSelectedItem("");
                    obsText.setText("");
                    suppBtn.setEnabled(true);
                    addBtn.setEnabled(false);
                    modBtn.setEnabled(false);
                    

   
             }
  
           
    }//GEN-LAST:event_tableMouseReleased

