   private void envoyerMessage(){
       message msg=new message();
        if(!MsgTxt.getText().isEmpty()){
        Date date=new Date();
        msg.setDate(date);
        msg.setTexte(MsgTxt.getText());
        ClientTchat.SendMessage(MsgTxt.getText());
        dlm.addElement(msg);      
        MsgTxt.setText("");
        MsgTxt.requestFocus();
        
        int index=ListMessage.getModel().getSize(); 
        if (index>3)
        ListMessage.scrollRectToVisible(ListMessage.getCellBounds(index-3, index-1));

        }  
   }
   
   
 public static synchronized void playSound(final String url) {
  new Thread(new Runnable() {
  // The wrapper thread is unnecessary, unless it blocks on the
  // Clip finishing; see comments.
    public void run() {
      try {
        Clip clip = AudioSystem.getClip();
        AudioInputStream inputStream = AudioSystem.getAudioInputStream(
          new java.io.BufferedInputStream(Descussion.class.getResourceAsStream("/res/sound/" + url)));
        clip.open(inputStream);
        clip.start(); 
      } catch (Exception e) {
        System.err.println(e.getMessage());
      }
    }
  }).start();
}

